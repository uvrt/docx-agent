def page_size(page, orientation: str = "portrait") -> tuple[int, int]:
    """``(width, height)`` in twips: a name of :data:`PAGE_SIZES`, or ``(width, height)`` in
    points; landscape puts the longer side across."""
    if isinstance(page, str):
        if page not in PAGE_SIZES:
            raise ValueError(f"unknown page size {page!r}: one of {', '.join(PAGE_SIZES)}, or (width, height)")
        width, height = PAGE_SIZES[page]
    else:
        try:
            width, height = (round(float(side) * 20) for side in page)
        except (TypeError, ValueError):
            raise ValueError("a page size is a name or (width, height) in points") from None
        if not (1440 <= width <= 31680 and 1440 <= height <= 31680):
            raise ValueError("a page side is between 72 and 1584 points (Word's 1 to 22 inches)")
    if orientation not in ("portrait", "landscape"):
        raise ValueError("orientation is 'portrait' or 'landscape'")
    if orientation == "landscape":
        width, height = max(width, height), min(width, height)
    return width, height


def document_xml(width: int, height: int, orientation: str, locale: Locale) -> str:
    para_id, text_id = generate("word/document.xml", set(), 2)
    orient = ' w:orient="landscape"' if orientation == "landscape" else ""
    m = locale.margin
    return (_DECL + _root("w:document", _DOCUMENT_PREFIXES, _IGNORABLE + " wp14")
            + f'<w:body><w:p w14:paraId="{para_id}" w14:textId="{text_id}"/>'
            + f'<w:sectPr><w:pgSz w:w="{width}" w:h="{height}"{orient}/>'
            + f'<w:pgMar w:top="{m}" w:right="{m}" w:bottom="{m}" w:left="{m}" w:header="{locale.header}" '
            + f'w:footer="{locale.footer}" w:gutter="0"/><w:cols w:space="{locale.column_space}"/>'
            + '<w:docGrid w:linePitch="360"/></w:sectPr></w:body></w:document>')


def _rels(relationships: list[tuple[str, str, str]]) -> str:
    items = "".join(f'<Relationship Id="{rid}" Type="{kind}" Target="{target}"/>'
                    for rid, kind, target in relationships)
    return (_DECL + '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
            + items + "</Relationships>")


def _content_types(overrides: list[tuple[str, str]]) -> str:
    return (_DECL + '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
            f'<Default Extension="rels" ContentType="{CT_RELS}"/><Default Extension="xml" ContentType="application/xml"/>'
            + "".join(f'<Override PartName="/{part}" ContentType="{kind}"/>' for part, kind in overrides)
            + "</Types>")


def build(*, page="A4", orientation: str = "portrait", language: str = "en-US", locale: Locale | None = None,
          title: str | None = None, author: str | None = None, created: datetime | None = None) -> bytes:
    """The whole package of a new blank document, as bytes."""
    from .properties import app_xml, core_xml

    if locale is None:
        locale = US if page == "Letter" else METRIC
    width, height = page_size(page, orientation)
    created = (created or datetime.now(timezone.utc)).replace(microsecond=0)
    parts = [
        ("_rels/.rels", _rels([("rId3", REL_APP, "docProps/app.xml"), ("rId2", REL_CORE, "docProps/core.xml"),
                               ("rId1", _R + "officeDocument", "word/document.xml")])),
        ("word/document.xml", document_xml(width, height, orientation, locale)),
        ("word/_rels/document.xml.rels", _rels([("rId3", _R + "webSettings", "webSettings.xml"),
                                                ("rId2", _R + "settings", "settings.xml"),
                                                ("rId1", _R + "styles", "styles.xml"),
                                                ("rId5", _R + "theme", "theme/theme1.xml"),
                                                ("rId4", _R + "fontTable", "fontTable.xml")])),
        ("word/theme/theme1.xml", theme_xml()),
        ("word/settings.xml", settings_xml(language, locale)),
        ("word/styles.xml", styles_xml(language)),
        ("word/webSettings.xml", web_settings_xml()),
        ("word/fontTable.xml", font_table_xml()),
        ("docProps/core.xml", core_xml(title=title, author=author, created=created)),
        ("docProps/app.xml", app_xml()),
    ]
    overrides = [("word/document.xml", CT_DOCUMENT), ("word/styles.xml", CT_STYLES),
                 ("word/settings.xml", CT_SETTINGS), ("word/webSettings.xml", CT_WEB_SETTINGS),
                 ("word/fontTable.xml", CT_FONT_TABLE), ("word/theme/theme1.xml", CT_THEME),
                 ("docProps/core.xml", CT_CORE), ("docProps/app.xml", CT_APP)]
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
        for path, data in [("[Content_Types].xml", _content_types(overrides))] + parts:
            entry = zipfile.ZipInfo(path, date_time=(1980, 1, 1, 0, 0, 0))
            entry.compress_type = zipfile.ZIP_DEFLATED
            entry.create_system = 3  # ZipInfo stamps the platform; the same bytes everywhere
            archive.writestr(entry, data.encode("utf-8") if isinstance(data, str) else data)
    return buffer.getvalue()


