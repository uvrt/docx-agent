"""A new document from nothing, written the way Word writes a new blank document.

Every part is authored here, from the values in :mod:`.word_new` (generated by
``tools/e6_probe.py`` from a new blank document Word 16.106 for Mac made with ``make new
document`` and saved) and the tables below; nothing is copied from Word's template or the
user's ``Normal.dotm`` (ROADMAP.md, "Decisions", 4).  What Word writes, and so what is
written here:

* ``document.xml``: one empty paragraph and the section -- the page size, the margins,
  the header and footer distances, ``w:cols`` and ``w:docGrid w:linePitch="360"``;
* ``styles.xml``: the document defaults (the theme's minor font at 12 pt, kerning from
  1 pt, the language, contextual ligatures; 8 pt after, line spacing 278 auto), the 376
  latent styles, and the styles a new document has: Normal, headings 1-9 and their linked
  character styles, Default Paragraph Font, Normal Table, No List, Title, Subtitle, Quote,
  List Paragraph, Intense Emphasis, Intense Quote and Intense Reference -- with English
  Word's ids and names;
* ``settings.xml``: zoom, the default tab stop, the hyphenation zone, character spacing
  control, compatibility mode 15 with the five settings Word writes beside it, the math
  settings, the theme font language, the colour mapping, the decimal symbol and the list
  separator;
* ``webSettings.xml``, ``fontTable.xml`` (Aptos, Times New Roman, Aptos Display);
* the Office theme (Aptos Display / Aptos, the 2023 colours), written here from its values;
* ``docProps/core.xml`` and ``docProps/app.xml``.

**What depends on the locale.**  Word's new document follows its Normal template, which
follows the interface's locale: this Word (Dutch interface, metric) makes an A4 page with
2.5 cm margins (1417 twips), header and footer at 708, a default tab stop of 708 and a
hyphenation zone of 425, the decimal comma and the list separator ``;``.  :class:`Locale`
holds those values; :data:`METRIC` is the measured one and the default, :data:`US` is
English (United States) Word's (Letter, 1-inch margins, half-inch tabs and distances, no
hyphenation zone written, ``.`` and ``,``: Word's well-known defaults, not measured on this
machine).  The text language (``w:lang``, ``w:themeFontLang``) is a parameter of its own.

Left out on purpose: rsids (ROADMAP.md, "Decisions", 6) and ``w15:docId``, which Word adds
when it saves; ``w:view`` (Word writes the window's view, here Draft -- a file without one
opens in Print Layout); Word's localised names (the theme's "Kantoorthema", the linked
styles' "Kop 1 Char"), where English Word's are written.
"""

