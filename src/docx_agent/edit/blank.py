def _root(tag: str, prefixes: tuple[str, ...], ignorable: str | None = _IGNORABLE) -> str:
    declarations = " ".join(f'xmlns:{prefix}="{_NS[prefix]}"' for prefix in prefixes)
    return f"<{tag} {declarations}" + (f' mc:Ignorable="{ignorable}"' if ignorable else "") + ">"


def _escape(text: str) -> str:
    return (text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
            .replace('"', "&quot;"))


def _xml(node: tuple) -> str:
    """An element from :mod:`.word_new`'s ``(tag, attributes, children)``."""
    tag, attributes, children = node
    attrs = "".join(f' {name}="{_escape(value)}"' for name, value in attributes)
    if not children:
        return f"<{tag}{attrs}/>"
    return f"<{tag}{attrs}>" + "".join(_xml(child) for child in children) + f"</{tag}>"


# -- styles ------------------------------------------------------------------------------------

#: English Word's ids where they are not the name's words run together.
_IDS = {"Normal Table": "TableNormal", "Default Paragraph Font": "DefaultParagraphFont", "No List": "NoList"}


def style_id(name: str) -> str:
    if name in _IDS:
        return _IDS[name]
    return "".join(word[:1].upper() + word[1:] for word in name.split())


def _with_language(node: tuple, language: str) -> tuple:
    tag, attributes, children = node
    if tag == "w:lang":
        attributes = tuple((k, language if k == "w:val" else v) for k, v in attributes)
    return (tag, attributes, tuple(_with_language(child, language) for child in children))


def _style_xml(entry: dict) -> str:
    flags = (' w:default="1"' if entry.get("default") else "") + (' w:customStyle="1"' if entry.get("custom") else "")
    out = [f'<w:style w:type="{entry["type"]}"{flags} w:styleId="{style_id(entry["name"])}">'
           f'<w:name w:val="{_escape(entry["name"])}"/>']
    for child in entry["children"]:
        if len(child) == 1:
            out.append(f"<{child[0]}/>")
        elif len(child) == 2:
            tag, value = child
            out.append(f'<{tag} w:val="{style_id(value) if isinstance(value, str) else value}"/>')
        else:
            out.append(_xml(child))
    out.append("</w:style>")
    return "".join(out)


def _latent_xml() -> str:
    attributes = "".join(f' {name}="{value}"' for name, value in word_new.LATENT_DEFAULTS)
    rows = []
    for name, priority, flags in word_new.LATENT:
        # Word's attribute order: name, locked, semiHidden, uiPriority, unhideWhenUsed, qFormat.
        attrs = f' w:name="{_escape(name)}"'
        attrs += ' w:locked="1"' if "l" in flags else ""
        attrs += ' w:semiHidden="1"' if "s" in flags else ""
        attrs += f' w:uiPriority="{priority}"' if priority is not None else ""
        attrs += ' w:unhideWhenUsed="1"' if "u" in flags else ""
        attrs += ' w:qFormat="1"' if "q" in flags else ""
        rows.append(f"<w:lsdException{attrs}/>")
    return f"<w:latentStyles{attributes}>" + "".join(rows) + "</w:latentStyles>"


def styles_xml(language: str) -> str:
    return (_DECL + _root("w:styles", ("mc", "r", "w") + _EXTENSIONS)
            + _xml(_with_language(word_new.DOC_DEFAULTS, language)) + _latent_xml()
            + "".join(_style_xml(entry) for entry in word_new.STYLES) + "</w:styles>")


# -- settings, web settings, fonts ---------------------------------------------------------------

_COMPAT_URI = "http://schemas.microsoft.com/office/word"


def settings_xml(language: str, locale: Locale) -> str:
    compat = "".join(f'<w:compatSetting w:name="{name}" w:uri="{_COMPAT_URI}" w:val="{value}"/>'
                     for name, value in word_new.COMPAT)
    mapping = "".join(f' {name}="{value}"' for name, value in word_new.COLOR_MAPPING)
    zone = f'<w:hyphenationZone w:val="{locale.hyphenation_zone}"/>' if locale.hyphenation_zone is not None else ""
    return (_DECL + _root("w:settings", ("mc", "o", "r", "m", "v", "w10", "w") + _EXTENSIONS + ("sl",))
            + '<w:zoom w:percent="100"/>'
            + f'<w:defaultTabStop w:val="{locale.tab_stop}"/>{zone}'
            + '<w:characterSpacingControl w:val="doNotCompress"/>'
            + f"<w:compat>{compat}</w:compat>" + _xml(word_new.MATH)
            + f'<w:themeFontLang w:val="{_escape(language)}"/><w:clrSchemeMapping{mapping}/>'
            + f'<w:decimalSymbol w:val="{_escape(locale.decimal_symbol)}"/>'
            + f'<w:listSeparator w:val="{_escape(locale.list_separator)}"/>'
            + "<w15:chartTrackingRefBased/></w:settings>")


def web_settings_xml() -> str:
    return (_DECL + _root("w:webSettings", ("mc", "r", "w") + _EXTENSIONS)
            + "".join(f"<{tag}/>" for tag in word_new.WEB_SETTINGS) + "</w:webSettings>")


def font_table_xml() -> str:
    return (_DECL + _root("w:fonts", ("mc", "r", "w") + _EXTENSIONS)
            + "".join(_xml(font) for font in word_new.FONTS) + "</w:fonts>")


